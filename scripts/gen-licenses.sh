#!/usr/bin/env bash
# Generates the THIRD-PARTY-LICENSES directory:
#   go/                 licence/notice texts of every Go dependency (go-licenses save) + go-licenses.csv report
#   images/<name>/      /usr/share/doc (per-package copyright files, FFmpeg COPYING.*, SOURCE-OFFER) and the dpkg
#                       package database of each shipped image, i.e. the base-image (Debian / distroless) notes
#   FFMPEG.txt          pinned FFmpeg version/hash, codec libraries, licence of the flavor and the source offer
#   README.txt          what is in here
# Usage: CONTAINER_RUNTIME=podman scripts/gen-licenses.sh <outdir> <flavor> api=<image> worker=<image> [postgres=<image>]
set -euo pipefail
cd "$(dirname "$0")/.."
. scripts/tool-versions.env
RT=${CONTAINER_RUNTIME:-docker}
out=$1 flavor=$2; shift 2
rm -rf "$out"; mkdir -p "$out/go" "$out/images"
go run "github.com/google/go-licenses@${GO_LICENSES_VERSION}" save ./... --save_path="$out/go/texts" --force
go run "github.com/google/go-licenses@${GO_LICENSES_VERSION}" report ./... > "$out/go/go-licenses.csv" 2>/dev/null
for spec in "$@"; do
  name=${spec%%=*} img=${spec#*=}
  d="$out/images/$name"; mkdir -p "$d"
  cid=$("$RT" create "$img" /nonexistent 2>/dev/null)
  "$RT" cp "$cid:/usr/share/doc" "$d/doc" 2>/dev/null || echo "note: $img has no /usr/share/doc" > "$d/NO-DOC.txt"
  for p in /var/lib/dpkg/status /var/lib/dpkg/status.d; do "$RT" cp "$cid:$p" "$d/$(basename "$p")" 2>/dev/null || true; done
  "$RT" rm -v "$cid" >/dev/null   # -v: do not leak the image's anonymous volumes (postgres declares one)
  printf '%s\n' "$img" > "$d/IMAGE.txt"
done
. docker/ffmpeg.env
{
  echo "FFmpeg $FFMPEG_VERSION (source tarball SHA-256 $FFMPEG_SHA256), built unmodified from https://ffmpeg.org/releases/."
  echo "Flavor shipped in this release: $flavor"
  if [ "$flavor" = lgpl ]; then
    echo "  LGPL v2.1 or later; configured without --enable-gpl/--enable-nonfree/--enable-version3 (asserted at image build time)."
  else
    echo "  FULL flavor: GPL v3 or later (x264/x265, --enable-gpl --enable-version3). Patent notice applies, see SOURCE-OFFER.txt."
  fi
  echo "Linked codec libraries: libsvtav1, libaom, libvpx, libopus, libvorbis, libmp3lame (+ libx264, libx265 in the full flavor);"
  echo "their licence files are under images/worker/doc/. License texts: images/worker/doc/ffmpeg/COPYING.*"
  echo
  cat docker/SOURCE-OFFER.txt
} > "$out/FFMPEG.txt"
cat > "$out/README.txt" <<R
Third-party licences shipped with ConvertFlow ${flavor} (generated by scripts/gen-licenses.sh)
  go/texts/           licence and notice files of the Go modules compiled into convertflow-api / convertflow-worker
  go/go-licenses.csv  module, licence URL, SPDX type (policy: scripts/check-licenses.sh, permissive licences only)
  images/<name>/      per-image Debian/distroless package copyright files and package lists (base-image notes)
  FFMPEG.txt          FFmpeg and codec libraries, licence of the flavor, written source offer
PostgreSQL (postgres image) is under the PostgreSQL License; its notices are in images/postgres when included.
The UI build tools (esbuild, typescript) are build-time only and are not distributed.
R
du -sh "$out"
